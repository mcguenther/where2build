-- The administration area: who may open it, who is blocked, what this
-- deployment did, and what an administrator changed.
--
-- The first migration file, and the reason `schema.sql` said one was due
-- before the first change to anything in it: two of the statements below alter
-- `users`, and `create table if not exists` says nothing about a table it
-- finds. Everything from here on is a numbered file, applied once, in order,
-- and recorded in `schema_migrations` -- see `app/services/storage.py`.
-- `schema.sql` stays what it is: the baseline, still applied on every start,
-- and not to be edited again.

-- The identifier every other part of the application already uses for an
-- account: sha256(issuer + "\n" + subject), first 32 hex characters, which is
-- `Identity.account_key`. `users` was keyed by issuer and subject, so nothing
-- could look a row up by the identifier the session cookie, the API and the
-- request budget all carry.
--
-- Backfilled here and written by the application from then on, rather than
-- generated by Postgres: `convert_to` is stable rather than immutable, so the
-- generated column Postgres will not accept would have been the obvious way to
-- make the two spellings unable to drift. `not null` is the guard that
-- replaces it -- an insert that forgets the column fails instead of leaving a
-- row nobody can find.
alter table users add column if not exists kennung text;

update users
   set kennung = substr(encode(sha256(convert_to(issuer || E'\n' || subject, 'UTF8')), 'hex'), 1, 32)
 where kennung is null;

alter table users alter column kennung set not null;

create unique index if not exists users_kennung_idx on users (kennung);

-- Who may open /verwaltung. `ADMIN_ACCOUNTS` is the bootstrap and is never
-- written here, so the way back in survives an empty table; everybody promoted
-- in the interface carries this flag.
alter table users add column if not exists ist_admin boolean not null default false;


-- A blocked account. Keyed by the account key rather than by `users.id`,
-- because the row in `users` is created on first *write* and somebody worth
-- blocking is precisely somebody who is spending this deployment's upstream
-- budget without necessarily having stored anything.
--
-- An end date, never a flag: a block that has to be lifted by hand is one that
-- is forgotten on. The sweep removes what is past it, and until it runs an
-- expired row simply does not block -- the comparison is against `bis`.
create table if not exists sperren (
    kennung     text        primary key,
    bis         timestamptz not null,
    grund       text        not null,
    -- Set by the burst guard rather than by a person. Kept apart so the
    -- interface can say which it was, and so an operator can tell a defence
    -- that fired from a decision somebody made.
    automatisch boolean     not null default false,
    angelegt    timestamptz not null default now(),
    -- The account key of the administrator who set it; null when automatic.
    durch       text
);

create index if not exists sperren_bis_idx on sperren (bis);


-- What this deployment did, per hour, with nobody in it. One row per hour,
-- area, service and outcome: the area separates a route of this API
-- („anfrage") from a call that went out to somebody else's („dienst") and from
-- the model („modell"), which is the distinction every question an operator
-- has starts from.
--
-- Counted rather than logged: a row per request would be the same numbers at a
-- thousand times the size, and it would hold when each single call happened,
-- which nobody needs and everybody would have to protect.
create table if not exists nutzung (
    stunde     timestamptz not null,
    bereich    text        not null,
    dienst     text        not null,
    ergebnis   text        not null,
    anzahl     bigint      not null default 0,
    -- Summed, not averaged: an average of averages is not an average, and the
    -- mean over any period is this divided by `anzahl`.
    dauer_ms   bigint      not null default 0,
    tokens_ein bigint      not null default 0,
    tokens_aus bigint      not null default 0,
    primary key (stunde, bereich, dienst, ergebnis)
);

create index if not exists nutzung_stunde_idx on nutzung (stunde);


-- The same per hour and account. This is the half that answers "who", and it
-- is the reason the table holds an account key and no name: it says how much
-- somebody used, never what they looked at.
create table if not exists nutzung_konto (
    stunde     timestamptz not null,
    kennung    text        not null,
    anzahl     bigint      not null default 0,
    fehler     bigint      not null default 0,
    tokens_ein bigint      not null default 0,
    tokens_aus bigint      not null default 0,
    primary key (stunde, kennung)
);

create index if not exists nutzung_konto_stunde_idx on nutzung_konto (stunde);


-- The failures, one row each, because this is the one place where the single
-- case is the point. `meldung` is the German sentence the caller was given --
-- the same one, so what an operator reads is what the user read.
create table if not exists fehler (
    id      bigserial   primary key,
    zeit    timestamptz not null default now(),
    bereich text        not null,
    dienst  text,
    status  integer,
    route   text,
    kennung text,
    meldung text        not null
);

create index if not exists fehler_zeit_idx on fehler (zeit desc);


-- What an administrator did. Survives the red button on purpose: a wipe that
-- erases the record of who wiped is not a record at all.
create table if not exists pruefprotokoll (
    id      bigserial   primary key,
    zeit    timestamptz not null default now(),
    kennung text        not null,
    name    text,
    aktion  text        not null,
    ziel    text,
    details jsonb
);

create index if not exists pruefprotokoll_zeit_idx on pruefprotokoll (zeit desc);
